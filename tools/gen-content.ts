// Writes an index.gen.ts in each content folder that holds one file per entry (enemies/<pool>/<id>.json,
// bosses/<id>.json): one import per file, so the rules stay free of bundler globs and Node APIs while
// hundreds of files are added (SPEC §14.1). `npm run gen:content` rewrites them; tools/content.test.ts
// fails while one is stale.
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const CONTENT = join(root, "src/shared/games/sovereign-pact/content");

/** The folders indexed, each with its index file. */
export const INDEXED = ["enemies", "bosses", "town", "expedition"].map((folder) => ({ folder, dir: join(CONTENT, folder), index: join(CONTENT, folder, "index.gen.ts") }));

const walk = (dir: string): string[] =>
  readdirSync(dir)
    .sort()
    .flatMap((name) => {
      const p = join(dir, name);
      return statSync(p).isDirectory() ? walk(p) : [p];
    });

/** The index file's text for the JSON files under `dir`, sorted by path. */
export function renderIndex(folder: string, dir: string): string {
  const files = walk(dir)
    .filter((f) => f.endsWith(".json"))
    .map((f) => relative(dir, f).split(sep).join("/"));
  const name = (f: string) => f.split("/").at(-1)!.replace(/\.json$/, "");
  return [
    `// Generated by \`npm run gen:content\` from content/${folder}/. Do not edit.`,
    ...files.map((f) => `import ${name(f)} from "./${f}" with { type: "json" };`),
    "",
    "export default [",
    ...files.map((f) => `  ${name(f)},`),
    "];",
    "",
  ].join("\n");
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  for (const { folder, dir, index } of INDEXED) {
    writeFileSync(index, renderIndex(folder, dir));
    console.log(`wrote ${relative(root, index)}`);
  }
}
