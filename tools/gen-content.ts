// Writes content/enemies/index.gen.ts: one import per enemy file, so the rules stay free of bundler
// globs and Node APIs while hundreds of enemy files are added (SPEC §14.1). `npm run gen:content`
// rewrites it; tools/content.test.ts fails while it is stale.
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
export const ENEMY_DIR = join(root, "src/shared/games/sovereign-pact/content/enemies");
export const ENEMY_INDEX = join(ENEMY_DIR, "index.gen.ts");

const walk = (dir: string): string[] =>
  readdirSync(dir)
    .sort()
    .flatMap((name) => {
      const p = join(dir, name);
      return statSync(p).isDirectory() ? walk(p) : [p];
    });

/** The index file's text for the enemy files on disk, sorted by pool then id. */
export function renderEnemyIndex(): string {
  const files = walk(ENEMY_DIR)
    .filter((f) => f.endsWith(".json"))
    .map((f) => relative(ENEMY_DIR, f).split(sep).join("/"));
  const name = (f: string) => f.split("/").at(-1)!.replace(/\.json$/, "");
  return [
    "// Generated by `npm run gen:content` from content/enemies/<pool>/<id>.json. Do not edit.",
    ...files.map((f) => `import ${name(f)} from "./${f}" with { type: "json" };`),
    "",
    "export default [",
    ...files.map((f) => `  ${name(f)},`),
    "];",
    "",
  ].join("\n");
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  writeFileSync(ENEMY_INDEX, renderEnemyIndex());
  console.log(`wrote ${relative(root, ENEMY_INDEX)}`);
}
